"""Externally judged CLI/data gate for sqlite-migrations-v2.

Twelve candidate CLI steps and three clean SQLite observers supplement the original
canonical tests. Expected values and comparisons stay in this controller. The
candidate receives only migration inputs and ordinary CLI arguments.

Covered: missing/existing dry-run, prefix application, resume/idempotency,
batch rollback, history drift, invalid target, duplicate-version discovery,
and literal database filenames beginning with ``file:``.
Not a replacement for the canonical API tests: caller-owned transactions,
autocommit=True, object validation, and the complete invalid-input matrix are
not independently observed here. Candidate code never executes on this host.
"""

import hashlib
import json
import shlex


def _same(actual, expected):
    """JSON equality without Python's True == 1 or 1.0 == 1 coercions."""
    try:
        return json.dumps(actual, sort_keys=True, allow_nan=False) == json.dumps(
            expected, sort_keys=True, allow_nan=False
        )
    except (TypeError, ValueError):
        return False


def _cli(gate, name, case, expected=None, error=False):
    result = case.result
    stdout = result.get("stdout", "")
    stderr = result.get("stderr", "")
    details = {
        "returncode": result.get("returncode"),
        "stdout": stdout,
        "stderr": stderr,
        "stopped_by": result.get("stopped_by"),
    }
    if error:
        passed = (
            type(result.get("returncode")) is int
            and result["returncode"] == 2
            and stdout == ""
            and isinstance(stderr, str)
            and bool(stderr.strip())
            and "Traceback" not in stderr
            and result.get("stopped_by") is None
        )
    else:
        try:
            actual = gate.json(case)
        except (ValueError, TypeError) as exc:
            actual = None
            details["decode_error"] = str(exc)
        details.update(actual=actual, expected=expected)
        passed = (
            type(result.get("returncode")) is int
            and result["returncode"] == 0
            and stderr == ""
            and result.get("stopped_by") is None
            and _same(actual, expected)
        )
    gate.record(name, passed, details)


def _bytes(gate, case, path):
    try:
        return gate.read(case, path)
    except (OSError, ValueError):
        return None


def _unchanged(gate, name, before, case, path):
    after = _bytes(gate, case, path)
    gate.record(
        name,
        before is not None and after is not None and before == after,
        {
            "path": path,
            "before_sha256": hashlib.sha256(before).hexdigest()
            if before is not None
            else None,
            "after_sha256": hashlib.sha256(after).hexdigest()
            if after is not None
            else None,
        },
    )


def _write_command(files):
    """Trusted setup bytes become inputs; this contains no expected outcomes."""
    code = "from pathlib import Path; " + "; ".join(
        f"Path({path!r}).write_bytes({data!r})" for path, data in files.items()
    )
    return "python -I -S -c " + shlex.quote(code)


def _observe(gate, name, case, database, table, rows, ledger):
    # The observer is isolated from all candidate modules and owns these reads.
    # Table is generated by this controller as an ASCII identifier, never taken
    # from candidate JSON or database schema text.
    if _bytes(gate, case, database) is None:
        gate.record(name, False, {"error": "Required database missing or unreadable"})
        return
    actual = gate.observe_sqlite(
        case,
        database,
        [
            f'SELECT value FROM "{table}" ORDER BY rowid',
            "SELECT version,name,checksum FROM schema_migrations ORDER BY version",
            "SELECT name FROM sqlite_master WHERE type='table' "
            "AND name NOT LIKE 'sqlite_%' ORDER BY name",
        ],
    )
    expected = [rows, ledger, [[name] for name in sorted([table, "schema_migrations"])]]
    gate.record(name, _same(actual, expected), {"actual": actual, "expected": expected})


def check(gate):
    suffix = hashlib.sha256(gate.token().encode()).hexdigest()[:12]
    table = "values_" + suffix
    base = "probe_" + suffix
    directory = base + "/sql"
    database = base + "/state.sqlite"
    first_value, second_value, rolled_back_value = (
        "first_" + gate.token(),
        "second_" + gate.token(),
        "rolled_back_" + gate.token(),
    )

    def sql_literal(value):
        return "'" + value.replace("'", "''") + "'"

    first_sql = (
        f'CREATE TABLE "{table}"(value TEXT);\n'
        f'INSERT INTO "{table}" VALUES ({sql_literal(first_value)});\n'
    ).encode()
    second_sql = (
        f'INSERT INTO "{table}" VALUES ({sql_literal(second_value)});\n'
    ).encode()
    first_name, second_name = "0001_initial.sql", "0003_more.sql"
    setup = {
        f"{directory}/{first_name}": first_sql,
        f"{directory}/{second_name}": second_sql,
    }
    command = (
        "python -m migrator " + shlex.quote(directory) + " " + shlex.quote(database)
    )
    ledger = [
        [1, first_name, hashlib.sha256(first_sql).hexdigest()],
        [3, second_name, hashlib.sha256(second_sql).hexdigest()],
    ]

    # 1: A missing database must remain absent even though the plan is nonempty.
    missing = gate.case("migration_dry_missing", setup, command + " --dry-run")
    _cli(
        gate,
        "migration_dry_missing_result",
        missing,
        {"applied": [], "pending": [1, 3], "target": 3},
    )
    gate.record(
        "migration_dry_missing_absent",
        gate.absent(missing, database),
        {"path": database},
    )

    # 2: Apply a selected prefix and inspect committed data from a clean process.
    prefix = gate.step(missing, command + " --target 1")
    _cli(gate, "migration_prefix_result", prefix, {"applied": [1], "current": 1})
    _observe(
        gate,
        "migration_prefix_artifacts",
        prefix,
        database,
        table,
        [[first_value]],
        ledger[:1],
    )

    # 3: Planning an existing database must preserve its exact bytes.
    before = _bytes(gate, prefix, database)
    existing = gate.step(prefix, command + " --dry-run")
    _cli(
        gate,
        "migration_dry_existing_result",
        existing,
        {"applied": [1], "pending": [3], "target": 3},
    )
    _unchanged(gate, "migration_dry_existing_unchanged", before, existing, database)

    # 4-5: Resume across a numeric version gap, then repeat without writes.
    resumed = gate.step(existing, command)
    _cli(gate, "migration_resume_result", resumed, {"applied": [3], "current": 3})
    before = _bytes(gate, resumed, database)
    repeated = gate.step(resumed, command)
    _cli(gate, "migration_repeat_result", repeated, {"applied": [], "current": 3})
    _unchanged(gate, "migration_repeat_unchanged", before, repeated, database)
    _observe(
        gate,
        "migration_resume_artifacts",
        repeated,
        database,
        table,
        [[first_value], [second_value]],
        ledger,
    )

    # 6: A later failing migration must roll back earlier work in the same batch.
    failed_inputs = {
        f"{directory}/0005_transient.sql": (
            f'INSERT INTO "{table}" VALUES ({sql_literal(rolled_back_value)});\n'
            f'CREATE TABLE "transient_{suffix}"(x);\n'
        ).encode(),
        f"{directory}/0007_failure.sql": (
            f'INSERT INTO "missing_{suffix}" VALUES (1);\n'
        ).encode(),
    }
    failed = gate.step(repeated, _write_command(failed_inputs) + " && " + command)
    _cli(gate, "migration_failed_batch_result", failed, error=True)
    _observe(
        gate,
        "migration_rollback_artifacts",
        failed,
        database,
        table,
        [[first_value], [second_value]],
        ledger,
    )

    # 7: Planning must not execute the invalid pending SQL or alter the database.
    before = _bytes(gate, failed, database)
    failed_plan = gate.step(failed, command + " --dry-run")
    _cli(
        gate,
        "migration_failed_batch_plan",
        failed_plan,
        {"applied": [1, 3], "pending": [5, 7], "target": 7},
    )
    _unchanged(
        gate, "migration_failed_batch_plan_unchanged", before, failed_plan, database
    )

    # 8: Editing an applied migration must fail without changing committed state.
    edited = {f"{directory}/{first_name}": first_sql + b"-- changed history\n"}
    before = _bytes(gate, failed_plan, database)
    drifted = gate.step(failed_plan, _write_command(edited) + " && " + command)
    _cli(gate, "migration_history_drift_result", drifted, error=True)
    _unchanged(gate, "migration_history_drift_unchanged", before, drifted, database)
    # 9-10: Independent invalid-input cases still run if behavioral checks failed.
    target = gate.case(
        "migration_invalid_target", setup, command + " --dry-run --target 2"
    )
    _cli(gate, "migration_invalid_target_result", target, error=True)
    gate.record(
        "migration_invalid_target_absent",
        gate.absent(target, database),
        {"path": database},
    )
    duplicate_setup = {**setup, f"{directory}/0001_duplicate.sql": b"SELECT 1;\n"}
    duplicate = gate.case(
        "migration_duplicate_version", duplicate_setup, command + " --dry-run"
    )
    _cli(gate, "migration_duplicate_version_result", duplicate, error=True)
    gate.record(
        "migration_duplicate_version_absent",
        gate.absent(duplicate, database),
        {"path": database},
    )

    # Ordinary relative Linux filenames may contain a colon. This does not ask
    # the candidate to implement SQLite URI arguments or special connection modes.
    literal_name = "file:" + suffix + ".sqlite"
    literal = base + "/" + literal_name
    literal_command = (
        "cd "
        + shlex.quote(base)
        + " && PYTHONPATH=/workspace python -m migrator sql "
        + shlex.quote(literal_name)
        + " --dry-run"
    )
    literal_missing = gate.case("migration_literal_missing", setup, literal_command)
    _cli(
        gate,
        "migration_literal_missing_result",
        literal_missing,
        {"applied": [], "pending": [1, 3], "target": 3},
    )
    gate.record(
        "migration_literal_missing_absent",
        gate.absent(literal_missing, literal),
        {"path": literal},
    )
    prefix_bytes = _bytes(gate, prefix, database)
    if prefix_bytes is None:
        for name in (
            "migration_literal_existing_result",
            "migration_literal_existing_unchanged",
        ):
            gate.record(name, False, {"error": "Required prefix database missing"})
    else:
        literal_existing = gate.case(
            "migration_literal_existing",
            {**setup, literal: prefix_bytes},
            literal_command,
        )
        _cli(
            gate,
            "migration_literal_existing_result",
            literal_existing,
            {"applied": [1], "pending": [3], "target": 3},
        )
        _unchanged(
            gate,
            "migration_literal_existing_unchanged",
            prefix_bytes,
            literal_existing,
            literal,
        )
